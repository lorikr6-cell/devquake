#!/usr/bin/env node
/**
 * Scans plugins/* for packages with `"devquake": { "plugin": true }` and generates:
 *   apps/host/src/plugins/registry.generated.ts          (lazy loaders, server only)
 *   apps/host/src/plugins/registry.manifest.generated.ts (plain data, safe for proxy/config)
 *   apps/host/src/plugins/registry.changelog.generated.ts (each plugin's CHANGELOG.md text)
 * It also keeps apps/host/package.json dependencies in sync with the plugin list.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pluginsDir = path.join(root, 'plugins');
const hostDir = path.join(root, 'apps', 'host');
const outDir = path.join(hostDir, 'src', 'plugins');

/** Subdomains that can never be claimed by a plugin. */
export const RESERVED = [
  'www',
  'api',
  'app',
  'admin',
  'auth',
  'dashboard',
  'mail',
  'smtp',
  'ftp',
  'cdn',
  'static',
  'assets',
  'status',
  'docs',
  'dev',
  'staging',
  'cpanel',
  'webmail',
];
const ID_RE = /^[a-z][a-z0-9-]{0,30}[a-z0-9]$/;

function fail(msg) {
  console.error(`\n[registry] ERROR: ${msg}\n`);
  process.exit(1);
}

const plugins = [];
if (fs.existsSync(pluginsDir)) {
  for (const dirent of fs.readdirSync(pluginsDir, { withFileTypes: true })) {
    if (!dirent.isDirectory()) continue;
    const pkgPath = path.join(pluginsDir, dirent.name, 'package.json');
    if (!fs.existsSync(pkgPath)) continue;
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
    if (!pkg.devquake?.plugin) continue;

    const id = pkg.devquake.subdomain ?? dirent.name;
    if (!ID_RE.test(id)) fail(`plugin "${dirent.name}" has invalid subdomain "${id}"`);
    if (RESERVED.includes(id)) fail(`plugin "${dirent.name}" uses reserved subdomain "${id}"`);
    if (plugins.some((p) => p.id === id)) fail(`duplicate plugin subdomain "${id}"`);
    const changelogPath = path.join(pluginsDir, dirent.name, 'CHANGELOG.md');
    const changelog = fs.existsSync(changelogPath) ? fs.readFileSync(changelogPath, 'utf8') : '';
    plugins.push({ id, pkg: pkg.name, changelog });
  }
}
plugins.sort((a, b) => a.id.localeCompare(b.id));

const header = '// AUTO-GENERATED by scripts/generate-registry.mjs — DO NOT EDIT.\n';

const loaders = `${header}import type { PluginDefinition } from '@devquake/plugin-sdk';

export const pluginLoaders: Record<string, () => Promise<PluginDefinition>> = {
${plugins.map((p) => `  '${p.id}': () => import('${p.pkg}').then((m) => m.default),`).join('\n')}
};
`;

const manifest = `${header}
export const pluginSubdomains = ${JSON.stringify(plugins.map((p) => p.id))} as const;

export const pluginPackages: string[] = ${JSON.stringify(plugins.map((p) => p.pkg))};

export const reservedSubdomains = ${JSON.stringify(RESERVED)} as const;
`;

// Release notes: the raw Markdown, parsed at runtime by parseChangelog() from the SDK (ADR 0008).
const changelogs = `${header}
export const pluginChangelogSources: Record<string, string> = {
${plugins.map((p) => `  ${JSON.stringify(p.id)}: ${JSON.stringify(p.changelog)},`).join('\n')}
};
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'registry.generated.ts'), loaders);
fs.writeFileSync(path.join(outDir, 'registry.manifest.generated.ts'), manifest);
fs.writeFileSync(path.join(outDir, 'registry.changelog.generated.ts'), changelogs);

// Sync host dependencies
const hostPkgPath = path.join(hostDir, 'package.json');
const hostPkg = JSON.parse(fs.readFileSync(hostPkgPath, 'utf8'));
const deps = { ...hostPkg.dependencies };
for (const name of Object.keys(deps)) {
  if (name.startsWith('@devquake/plugin-') && name !== '@devquake/plugin-sdk') delete deps[name];
}
for (const p of plugins) deps[p.pkg] = 'workspace:*';
const sorted = Object.fromEntries(Object.entries(deps).sort(([a], [b]) => a.localeCompare(b)));

const changed = JSON.stringify(sorted) !== JSON.stringify(hostPkg.dependencies);
if (changed) {
  hostPkg.dependencies = sorted;
  fs.writeFileSync(hostPkgPath, `${JSON.stringify(hostPkg, null, 2)}\n`);
}

console.log(
  `[registry] ${plugins.length} plugin(s): ${plugins.map((p) => p.id).join(', ') || '(none)'}`,
);
if (changed) console.log('[registry] apps/host/package.json changed — run `pnpm install`.');
